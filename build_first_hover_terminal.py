#!/usr/bin/env python3
"""Generate the standalone terminal-11 controller without importing ROS.

Run from any directory. --check verifies the committed artifact without writing.
The controller and its dependencies remain the canonical editable sources.
"""
import argparse
import ast
from pathlib import Path


ROOT = Path(__file__).resolve().parent
HEADER = '# Generated by build_first_hover_terminal.py; edit canonical sources.\n'


def build():
    def tree(name):
        return ast.parse((ROOT / name).read_text())

    controller = tree('first_hover_control.py')
    pose = tree('ground_setpoint_transport.py')
    reference = tree('hover_reference.py')
    preview = tree('first_hover_preview.py')

    def definition(module, name):
        return next(node for node in module.body
                    if isinstance(node, (ast.ClassDef, ast.FunctionDef)) and node.name == name)

    def assignment(module, name):
        return next(node for node in module.body
                    if isinstance(node, ast.Assign) and any(
                        isinstance(target, ast.Name) and target.id == name for target in node.targets))

    imports = [node for node in controller.body if isinstance(node, (ast.Import, ast.ImportFrom))
               and not (isinstance(node, ast.ImportFrom) and node.module in
                        ('ground_setpoint_transport', 'first_hover_preview', 'hover_reference'))]
    nodes = imports + [assignment(preview, 'LIMITS')]
    nodes += [assignment(controller, name) for name in ('NATIVE', 'DEBUG', 'PARAMETERS')]
    nodes += [definition(reference, 'HoverReference'), definition(pose, 'pose_values'),
              definition(controller, 'FirstHoverControl'), definition(controller, 'main')]
    nodes.append(controller.body[-1])  # guarded main()
    module = ast.Module(body=nodes, type_ignores=[])
    code = HEADER + ast.unparse(ast.fix_missing_locations(module)) + '\n'
    compile(code, 'first_hover_terminal.py', 'exec')
    return code


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'first_hover_terminal.py'
    expected = build()
    if args.check:
        if not target.is_file() or target.read_text() != expected:
            raise SystemExit('Standalone controller differs; regenerate before publishing.')
        print('PASS: standalone controller matches canonical sources')
    else:
        target.write_text(expected)
        print('Generated:', target.name)


if __name__ == '__main__':
    main()
